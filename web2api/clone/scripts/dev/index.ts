import { spawn } from "node:child_process";
import { closeSync, existsSync, openSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { defaultConfigPath, loadOrCreateConfig, type DaemonConfig } from "../../src/daemon/config";

const lineEnding: string = "\r\n";
const devRoot: string = import.meta.dirname;
const cloneRoot: string = resolve(devRoot, "..", "..");
const distRoot: string = resolve(devRoot, "dist");
const daemonRuntimePath: string = resolve(distRoot, "web2api-daemon.cjs");
const daemonLogPath: string = resolve(distRoot, "daemon.log");
const extensionSourcePath: string = resolve(cloneRoot, "src", "extension", ".output", "chrome-mv3");
const vscodePath: string = "C:\\Users\\diyya\\AppData\\Local\\Programs\\Microsoft VS Code\\Code.exe";
const pnpmPath: string = "pnpm.cmd";

const envobj = {
  CODEX_HOME: resolve(distRoot, "codex-home"),
  WEB2API_MODEL: "chatgpt/default",
  USER_DATA_DIR: resolve(distRoot, "vscode-process")
};

function assertPath(path: string, description: string): void {
  if (!existsSync(path)) {
    throw new Error(`${description}不存在：${path}`);
  }
}

async function runPnpm(argumentsList: string[]): Promise<void> {
  const result = spawn(pnpmPath, argumentsList, { cwd: cloneRoot, shell: true, stdio: "inherit", windowsHide: true });
  await new Promise<void>((resolvePromise, reject): void => {
    result.once("error", reject);
    result.once("exit", (code: number | null): void => {
      if (code === 0) {
        resolvePromise();
        return;
      }
      reject(new Error(`pnpm ${argumentsList.join(" ")}执行失败，退出码：${code ?? "unknown"}`));
    });
  });
}

async function buildExtension(): Promise<void> {
  await runPnpm(["run", "build:extension"]);
  assertPath(extensionSourcePath, "扩展构建目录");
}

async function buildDaemon(): Promise<void> {
  await mkdir(distRoot, { recursive: true });
  await runPnpm([
    "exec",
    "esbuild",
    "src/daemon/cli.ts",
    "--bundle",
    "--platform=node",
    "--format=cjs",
    "--target=node22",
    `--outfile=${daemonRuntimePath}`
  ]);
}

async function isDaemonRunning(config: DaemonConfig): Promise<boolean> {
  try {
    const response: Response = await fetch(`http://127.0.0.1:${config.port}/v1/models`, {
      headers: { Authorization: `Bearer ${config.api_key}` },
      signal: AbortSignal.timeout(500)
    });
    return response.status === 200;
  } catch {
    return false;
  }
}

function startDaemon(configPath: string): void {
  const log: number = openSync(daemonLogPath, "a");
  const child = spawn(process.execPath, [daemonRuntimePath, "start", "--config", configPath], {
    cwd: cloneRoot,
    detached: true,
    stdio: ["ignore", log, log],
    windowsHide: true
  });
  child.unref();
  closeSync(log);
}

async function waitForDaemon(config: DaemonConfig): Promise<void> {
  const deadline: number = Date.now() + 10_000;
  while (Date.now() < deadline) {
    if (await isDaemonRunning(config)) {
      return;
    }
    await new Promise<void>((resolvePromise): void => {
      setTimeout(resolvePromise, 200);
    });
  }
  throw new Error(`Web2API daemon 未能启动，请查看日志：${daemonLogPath}`);
}

async function ensureDaemon(configPath: string): Promise<DaemonConfig> {
  const config: DaemonConfig = await loadOrCreateConfig(configPath, {});
  if (await isDaemonRunning(config)) {
    return config;
  }
  await buildDaemon();
  startDaemon(configPath);
  await waitForDaemon(config);
  return config;
}

function startVsCode(apiKey: string): void {
  const child = spawn(vscodePath, ["--new-window", "--user-data-dir", envobj.USER_DATA_DIR], {
    cwd: distRoot,
    detached: true,
    env: { ...process.env, ...envobj, WEB2API_KEY: apiKey },
    stdio: "ignore",
    windowsHide: false
  });
  child.unref();
}

async function main(): Promise<void> {
  if (process.platform !== "win32") {
    throw new Error("这个启动器只支持 Windows。");
  }

  assertPath(vscodePath, "VS Code 可执行文件");
  await mkdir(distRoot, { recursive: true });
  await mkdir(envobj.CODEX_HOME, { recursive: true });
  await mkdir(envobj.USER_DATA_DIR, { recursive: true });

  await buildExtension();
  const daemonConfig: DaemonConfig = await ensureDaemon(defaultConfigPath());
  const baseUrl: string = `http://127.0.0.1:${daemonConfig.port}/v1`;
  const configContent: string = [
    "# Generated by scripts/dev/index.ts",
    `model = "${envobj.WEB2API_MODEL}"`,
    'model_provider = "web2api"',
    "",
    "[model_providers.web2api]",
    'name = "Web2API"',
    `base_url = "${baseUrl}"`,
    'wire_api = "responses"',
    'env_key = "WEB2API_KEY"',
    "requires_openai_auth = false",
    "supports_websockets = false",
    ""
  ].join(lineEnding);
  await writeFile(resolve(envobj.CODEX_HOME, "config.toml"), configContent, "utf8");
  startVsCode(daemonConfig.api_key);

  console.log(`扩展：${extensionSourcePath}`);
  console.log(`Web2API daemon：${baseUrl}`);
  console.log(`Codex Home：${envobj.CODEX_HOME}`);
  console.log(`配置文件：${resolve(envobj.CODEX_HOME, "config.toml")}`);
  console.log(`隔离 VS Code：${envobj.USER_DATA_DIR}`);
  console.log(`daemon 日志：${daemonLogPath}`);
}

main().catch((error: unknown): void => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
